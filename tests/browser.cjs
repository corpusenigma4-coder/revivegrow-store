"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {chromium}=require("playwright-core");
const BASE="http://127.0.0.1:8765/";
async function run(){
  const executablePath=process.env.CHROME||"/usr/bin/google-chrome";
  const browser=await chromium.launch({headless:true,executablePath,args:["--no-sandbox","--disable-dev-shm-usage"]});
  const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  const errors=[];
  page.on("pageerror",err=>errors.push(err.message));
  await page.goto(BASE+"index.html",{waitUntil:"domcontentloaded"});
  await page.locator("#productGrid .card").first().waitFor();
  assert.equal(await page.locator("#productGrid .card").count(),4,"All four catalog designs should be visible");
  assert.equal(await page.locator("#productGrid a.card").count(),2,"Bunny Dream and Pumpkin Dream must both open detail pages");
  assert.equal(await page.locator("#productGrid article.card--coming").count(),2,"Only unfinished designs are coming soon");
  assert.ok((await page.locator("#productGrid a.card").getAttribute("href")).includes("slug=conejito"));
  assert.equal(await page.locator(".card__concept").count(),2,"Two preview-only designs show concept labels");
  assert.equal(await page.locator("#catalogCount").textContent(),"4 diseños en esta selección");
  assert.ok((await page.locator('#productGrid a.card[href="producto.html?slug=calabaza"]').textContent()).includes("19.35"),"Pumpkin catalog card must have real $19.35 price");
  await page.locator("#productGrid .card").first().scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>[...document.querySelectorAll("#productGrid .card img")].every(img=>img.complete&&img.naturalWidth>0));
  assert.ok(await page.locator("#productGrid .card img").evaluateAll(imgs=>imgs.every(i=>i.complete&&i.naturalWidth>0)),"Product images must load");
  await page.screenshot({path:"screenshots/home-full-desktop.png",fullPage:true});
  await page.locator('#filters button[data-section="halloween"]').click();
  assert.equal(await page.locator("#productGrid .card").count(),2,"Halloween contains Pumpkin Dream and a future design");
  assert.equal(await page.locator('#productGrid a.card[href="producto.html?slug=calabaza"]').count(),1,"Pumpkin Dream must be a clickable Halloween product");
  await page.locator('#filters button[data-section="navidad"]').click();
  assert.equal(await page.locator("#productGrid .card").count(),0,"Christmas must be empty until product data exists");
  assert.ok((await page.locator(".empty-state").textContent()).includes("Navidad"));
  await page.locator('#filters button[data-section="todo"]').click();
  await page.locator("#searchToggle").click();
  await page.locator("#searchInput").fill("conejito");
  assert.equal(await page.locator("#productGrid .card").count(),1,"Search should filter products");
  await page.goto(BASE+"index.html?coleccion=navidad#catalogo",{waitUntil:"domcontentloaded"});
  assert.equal(await page.locator("#productGrid .card").count(),0,"Christmas collection pending");
  await page.goto(BASE+"producto.html?slug=conejito",{waitUntil:"domcontentloaded"});
  await page.locator(".pp-name").waitFor();
  assert.ok((await page.locator(".pp-name").textContent()).includes("Bunny Dream"));
  assert.equal(await page.locator(".gallery__thumb").count(),5,"Five real photo views");
  await page.waitForFunction(()=>Array.from(document.querySelectorAll(".gallery__thumb img")).every(el=>el.complete && el.naturalWidth >= 800));
  await page.locator(".gallery__thumb").nth(2).click();
  assert.ok((await page.locator(".gallery__img").getAttribute("src")).includes("bunny-hood.webp"),"Third photo should show hood close-up");
  await page.locator(".gallery__thumb").first().click();
  assert.ok((await page.locator(".gallery__img").getAttribute("src")).includes("bunny-front.webp"),"First photo should show front");
  assert.equal(await page.locator("#sizes .size").count(),5);
  await page.locator("#sizeGuideAcc").evaluate(el=>el.open=true);
  assert.equal(await page.locator(".sizeguide tbody tr").count(),5);
  assert.ok((await page.locator(".pp-fulfillment").textContent()).includes("90 días"));
  assert.ok(await page.locator(".gallery__img").evaluate(el=>el.naturalWidth>=800),"Main product photo must be high resolution");
  await page.screenshot({path:"screenshots/product-desktop.png",fullPage:true});
  await page.locator('#sizes .size:not([disabled])').first().click();
  assert.equal(await page.locator("#addBtn").isDisabled(),false);
  await page.locator("#addBtn").click();
  assert.ok(await page.locator("#cartDrawer").evaluate(el=>el.classList.contains("is-open")),"Cart drawer should open");
  assert.ok((await page.locator("#cartFoot").textContent()).includes("23.55"),"Subtotal accurate");
  assert.ok((await page.locator("#cartFoot").textContent()).includes("en preparación"),"PayPal stays disabled");
  await page.locator("#cartClose").click();
  // Second published product: gallery, sizes, price, policy, cart and image fidelity.
  await page.goto(BASE+"producto.html?slug=calabaza",{waitUntil:"domcontentloaded"});
  await page.locator(".pp-name").waitFor();
  assert.ok((await page.locator(".pp-name").textContent()).includes("Pijama Calabacita"));
  assert.ok((await page.locator(".pp-price").textContent()).includes("19.35"));
  assert.equal(await page.locator(".gallery__thumb").count(),5,"Pumpkin Dream five separate photos");
  await page.waitForFunction(()=>[...document.querySelectorAll(".gallery__thumb img")].every(im=>im.complete&&im.naturalWidth>=800&&im.naturalHeight>=1000));
  await page.locator(".gallery__thumb").nth(3).click();
  assert.ok((await page.locator(".gallery__img").getAttribute("src")).includes("pumpkin-baby-crawling.webp"));
  await page.locator(".gallery__thumb").nth(4).click();
  assert.ok((await page.locator(".gallery__img").getAttribute("src")).includes("pumpkin-baby-sitting.webp"));
  await page.locator(".gallery__thumb").first().click();
  assert.equal(await page.locator("#sizes .size").count(),5);
  await page.locator("#sizeGuideAcc").evaluate(el=>el.open=true);
  assert.equal(await page.locator(".sizeguide tbody tr").count(),5);
  assert.ok((await page.locator(".pp-fulfillment").textContent()).includes("90 días"));
  assert.ok((await page.locator(".pp-fulfillment").textContent()).includes("todo el mundo"));
  await page.locator('#sizes .size:not([disabled])').nth(2).click();
  assert.equal(await page.locator("#addBtn").isDisabled(),false);
  await page.locator("#addBtn").click();
  assert.ok((await page.locator("#cartFoot").textContent()).includes("19.35"),"Pumpkin Dream subtotal");
  assert.ok((await page.locator("#cartFoot").textContent()).includes("en preparación"),"PayPal still disabled");
  await page.locator("#cartClose").click();
  await page.goto(BASE+"producto.html?slug=does-not-exist",{waitUntil:"domcontentloaded"});
  assert.ok((await page.locator("#productRoot").textContent()).includes("Producto no encontrado"),"Unknown product fallback");
  const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  mobile.on("pageerror",err=>errors.push(err.message));
  await mobile.goto(BASE+"index.html",{waitUntil:"domcontentloaded"});
  await mobile.locator("#productGrid .card").first().waitFor();
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+3),"No horizontal overflow on mobile");
  await mobile.screenshot({path:"screenshots/home-full-mobile.png",fullPage:true});
  await mobile.locator("#burger").click();
  assert.equal(await mobile.locator("#mobileNav").isVisible(),true,"Mobile menu opens");
  await mobile.locator('#mobileNav a[href="#catalogo"]').click();
  assert.equal(await mobile.locator("#mobileNav").isVisible(),false,"Mobile menu closes on navigation");
  await mobile.goto(BASE+"producto.html?slug=conejito",{waitUntil:"domcontentloaded"});
  await mobile.locator(".pp-name").waitFor();
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+3),"No horizontal overflow on mobile product");
  await mobile.screenshot({path:"screenshots/product-mobile.png",fullPage:true});
  assert.deepEqual(errors,[],"No uncaught JavaScript errors");
  await browser.close();
  console.log("OK: Bunny Dream and Pumpkin Dream catalog, high-res photo galleries, 5 sizes, shipping, returns, cart, PayPal disabled, and responsive navigation.");
}
run().catch(err=>{console.error(err);process.exit(1)});
